import { contextBridge, ipcRenderer } from "electron"

const on = (channel: string) => (cb: (data: any) => void) => {
  const fn = (_: unknown, data: unknown) => cb(data)
  ipcRenderer.on(channel, fn)
  return () => void ipcRenderer.removeListener(channel, fn)
}

