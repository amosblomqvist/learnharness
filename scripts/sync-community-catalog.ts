import { mkdirSync, readFileSync, writeFileSync, renameSync, rmSync } from "node:fs";
import { dirname, resolve } from "node:path";
import ts from "typescript";
import { randomUUID } from "node:crypto";
import coreIds from "../core-plugins.json";
import { COMMUNITY_FEED_LIMIT, parseCommunityFeed } from "../src/core/community-catalog.ts";

const args = process.argv.slice(2);
const check = args[0] === "--check";
if (check) args.shift();
if (args.length !== 1) throw new Error("Usage: tsx scripts/sync-community-catalog.ts [--check] <website-checkout>");
const site = resolve(args[0]!);
const config = JSON.parse(readFileSync(resolve(site, "wrangler.jsonc"), "utf8"));
if (config.name !== "learnharness-web") throw new Error("Expected a LearnHarness website checkout");
const bytes = readFileSync(new URL("../plugin-catalog/community-plugins.json", import.meta.url));
if (bytes.length > COMMUNITY_FEED_LIMIT) throw new Error("Catalog exceeds public feed size limit");
parseCommunityFeed(JSON.parse(new TextDecoder("utf-8", { fatal: true }).decode(bytes)), coreIds);
const source = readFileSync(new URL("../src/core/community-catalog.ts", import.meta.url), "utf8");
const script = ts.transpileModule(`${source}\nexport const parseWebsiteCommunityFeed = (data: unknown) => parseCommunityFeed(data, ${JSON.stringify(coreIds)});\n`, {
	fileName: "community-catalog.ts",
	compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022, newLine: ts.NewLineKind.LineFeed, sourceMap: false },
});
const contract = Buffer.from(`// Generated by the app's scripts/sync-community-catalog.ts. Do not edit.\n${script.outputText}`);
for (const [name, content] of [["community-plugins.json", bytes], ["plugins/catalog-contract.js", contract]] as const) {
	const destination = resolve(site, name);
	let unchanged = false;
	try { unchanged = content.equals(readFileSync(destination)); }
	catch (error) { if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error; }
	if (!unchanged) {
		if (check) throw new Error(`Website catalog artifact is out of sync: ${name}`);
		mkdirSync(dirname(destination), { recursive: true });
		const temporary = `${destination}.${randomUUID()}.tmp`;
		try { writeFileSync(temporary, content, { flag: "wx" }); renameSync(temporary, destination); }
		finally { rmSync(temporary, { force: true }); }
	}
	console.log(`${check ? "Verified" : "Synced"} ${destination}`);
}
